package com.forsy.model.enums;

/**
 * Enumeration representing the primary languages supported by the bookstore.
 *
 * <p>Used to categorize book titles and help users filter the collection based
 * on their preferred linguistic requirements.
 *
 * @author Illia
 */
public enum Language {

  /**
   * The English language.
   */
  ENGLISH,

  /**
   * The Spanish language.
   */
  SPANISH,

  /**
   * The French language.
   */
  FRENCH,

  /**
   * The German language.
   */
  GERMAN,

  /**
   * The Japanese language.
   */
  JAPANESE,

  /**
   * The Ukrainian language.
   */
  UKRAINIAN,

  /**
   * Any other language not explicitly listed in this enumeration.
   */
  OTHER
}
